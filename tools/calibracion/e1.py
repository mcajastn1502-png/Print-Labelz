from lab import render, bbox
def t(name, body, **kw):
    img = render("^XA^LH0,0" + body + "^XZ", **kw)
    print(f"{name:40} {bbox(img)}")
# Text N
t("FO100,100 A0N50,50 HHHH", "^FO100,100^A0N,50,50^FDHHHH^FS")
